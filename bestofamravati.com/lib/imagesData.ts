function hashSlug(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function getCategoryBusinessImage(
  categorySlug: string = '',
  businessSlug: string = '',
  index: number = 0
): string {
  const pool = CATEGORY_COVER_IMAGES[categorySlug] || DEFAULT_IMAGES;
  const pickIndex = businessSlug
    ? (hashSlug(businessSlug) + index) % pool.length
    : index % pool.length;

  return pool[pickIndex];
}
